"""V6b, the pro forma threshold test (validation plan §V6; issue #49).

    uv run python scripts/archive/v6b_fee_threshold.py MN NC OH OR TX   # one state per process is lighter

For each state, from the processed tables (offline; outcomes holdout-filtered, none read here):

1. Lots crossing feasibility, at central parameters: on every place with a parcel roll (candidate vacant lots
   and a new-home value), how many lots the single-family prototype pencils out on before and after the cut
   (`fees.feasibility_change`). Two cuts: the Challenge benchmark ($50,000 per home cut by $25,000) and each
   place's real fee cut by half (the `fees_local_half` scenario).
2. The five-year response: homes added ÷ homes built anyway, by size (houses; 2-4 unit buildings), over the
   engine's draws (`fees.simulate`), P10 / P50 / P90, for both cuts, against the plan's literature range:
   0 to +12% for houses and 0 to +18% for small multifamily over 5 years.

Writes reports/v6b/<ST>.json; `--report` merges every state's JSON into reports/v6b/V6b-fee-threshold.md.
No parameter, model or config change.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "reports" / "v6b"
MODES = {"fees": "handbook", "fees_local_half": "local_half"}
LABEL = {
    "fees": "Challenge benchmark ($50,000 cut by $25,000)",
    "fees_local_half": "Real local fees cut by half",
}
RANGE = {"1": (0.0, 0.12), "2_4": (0.0, 0.18)}  # validation plan §V6, five years


def one_state(st: str) -> dict:
    from lotline.config import load_params
    from lotline.io import DataStore
    from lotline.io.offline import offline_build
    from lotline.model import fee_inputs
    from lotline.model.scenarios import fees

    store = DataStore()
    origin = int(load_params("aggregate")["results_origin_year"].value)
    with offline_build(store):
        places = fee_inputs.statewide_places(st, store, origin)
    p = fees.central_params()
    out = {"state": st, "origin": origin, "places": int(len(places)), "cuts": {}}
    has_lots = [
        isinstance(lots, np.ndarray | list) and len(lots) > 0 and np.isfinite(v)
        for lots, v in zip(places.get("lot_values", [None] * len(places)),
                           places.get("new_home_value", [np.nan] * len(places)), strict=True)
    ]  # fmt: skip
    for key, mode in MODES.items():
        fee, _ = fees.fee_levels(places, mode, p, "SFD")
        saving = fees.builder_saving(fee, p, mode)
        before = after = used = 0
        for i, ok in enumerate(has_lots):
            if not ok:
                continue
            _, b, a = fees.feasibility_change(
                float(places["new_home_value"].iloc[i]), float(fee[i]), float(saving[i]),
                places["lot_values"].iloc[i], p,
            )  # fmt: skip
            before, after = before + b, after + a
            used += b >= p["fee_feasibility_min_lots"]
        sim = fees.simulate(places, origin, mode=mode)
        resp = {}
        if sim["added_by_class"]:
            groups = {"1": ["1"], "2_4": ["2", "3_4"]}
            for g, cls in groups.items():
                added = sum(sim["added_by_class"][c].sum(axis=(1, 2)) for c in cls)
                base = sum(float(sim["by_size"][c].sum()) for c in cls)
                pct = added / base if base > 0 else np.full_like(added, np.nan)
                lo, hi = RANGE[g]
                p10, p50, p90 = (float(x) for x in np.percentile(pct, [10, 50, 90]))
                inside = float(np.mean((pct >= lo) & (pct <= hi)))
                resp[g] = {"p10": p10, "p50": p50, "p90": p90, "base_homes": base,
                           "p50_inside": lo <= p50 <= hi, "share_of_draws_inside": inside}  # fmt: skip
        out["cuts"][key] = {
            "label": LABEL[key],
            "fee_median": float(np.nanmedian(fee)),
            "saving_median": float(np.nanmedian(saving)),
            "places_with_lots": int(sum(has_lots)),
            "places_feasibility_route": int(used),
            "lots_feasible_before": int(before),
            "lots_feasible_after": int(after),
            "lots_crossing": int(after - before),
            "response": resp,
        }
    return out


def pct(x: float) -> str:
    return f"{x * 100:+.1f}%"


def cell(x) -> str:
    return "–" if not x else f"{pct(x['p10'])} / {pct(x['p50'])} / {pct(x['p90'])}"


def ok(x) -> str:
    if not x:
        return "–"
    return f"{'yes' if x['p50_inside'] else 'no'} ({x['share_of_draws_inside']:.0%} of draws)"


def report() -> Path:
    rows = [json.loads(f.read_text()) for f in sorted(OUT.glob("[A-Z][A-Z].json"))]
    lines = [
        "# V6b: the pro forma threshold test",
        "",
        "Validation plan §V6, issue #49. Generated by `scripts/archive/v6b_fee_threshold.py` from the processed",
        "tables (offline; no outcome read). Origin " + str(rows[0]["origin"] if rows else "") + ".",
        "",
        "## 1. Lots where a new house starts to pencil out",
        "",
        "Places with a parcel roll; single-family prototype at central parameters; a lot pencils out when",
        "the residual land value beats its assessed land value plus the existing-use margin.",
        "",
        "| State | Cut | Median fee | Median saving to builder | Places with lots | Lots before | Lots after "
        "| Crossing |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        for c in r["cuts"].values():
            lines.append(
                f"| {r['state']} | {c['label']} | ${c['fee_median']:,.0f} | ${c['saving_median']:,.0f} | "
                f"{c['places_with_lots']} | {c['lots_feasible_before']:,} | {c['lots_feasible_after']:,} | "
                f"{c['lots_crossing']:+,} |"
            )
    lines += [
        "",
        "## 2. Five-year response against the literature range",
        "",
        "Homes added ÷ homes built anyway over 2027-2031, P10 / P50 / P90 of the engine's draws. Plan range:",
        '0 to +12% for houses, 0 to +18% for 2-4 unit buildings. "Inside" = the P50 is in the range; the',
        "share of draws in the range is also given.",
        "",
        "| State | Cut | Houses P10 / P50 / P90 | Inside | 2-4 units P10 / P50 / P90 | Inside |",
        "|---|---|---|---|---|---|",
    ]
    verdicts = []
    for r in rows:
        for c in r["cuts"].values():
            h, m = c["response"].get("1"), c["response"].get("2_4")
            lines.append(f"| {r['state']} | {c['label']} | {cell(h)} | {ok(h)} | {cell(m)} | {ok(m)} |")
            verdicts += [x["p50_inside"] for x in (h, m) if x]
    passed = all(verdicts) if verdicts else False
    verdict = "pass" if passed else "review"
    n_in, n = sum(verdicts), len(verdicts)
    lines += ["", f"**Result:** {verdict}: {n_in} of {n} state-cut-size midpoints inside the range.", ""]
    lines += [
        "## Reading",
        "",
        "- The pass rule is weak on its own: the range starts at 0, so a small effect always passes. What",
        "  V6b shows is the size of the gap the plan asked about. Real local fees for a new house are a",
        "  fraction of the Handbook's $50,000, so halving them moves building far less than the $25,000",
        "  benchmark cut.",
        "- Lots crossing can be counted only where a parcel roll gives candidate vacant lots and a new-home",
        "  value (Minnesota and Oregon here). Elsewhere the engine uses the elasticity route, and only part",
        "  2 applies.",
        "- No fee cut in our states has been measured (V6a, the Carthage comparison, is still open), so the",
        "  range is the published one, not our own.",
        "",
    ]
    path = OUT / "V6b-fee-threshold.md"
    path.write_text("\n".join(lines))
    return path


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    args = sys.argv[1:]
    if args == ["--report"]:
        print(report())
    else:
        for st in args:
            res = one_state(st.upper())
            (OUT / f"{st.upper()}.json").write_text(json.dumps(res, indent=1))
            summary = {
                k: (c["lots_crossing"], {g: round(v["p50"], 4) for g, v in c["response"].items()})
                for k, c in res["cuts"].items()
            }
            print(st.upper(), summary)
