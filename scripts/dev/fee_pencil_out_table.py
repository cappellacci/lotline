#!/usr/bin/env python3
# ruff: noqa: E501  (long table lines)
"""Pencil-out table: house, duplex and fourplex pro formas per coded place, at today's fees and after a cut
(fee plan Phase 2, D-073; office hours 2026-11-03, A5). Writes a Markdown table; reads the data store.

    uv run python scripts/dev/fee_pencil_out_table.py [--origin 2025] [--state MN NC OH OR TX]
        [--out docs/research/fee-pencil-out.md]

Per place with coded fees (holdout places left out, as in fee_dev_run.py): fee per unit for each type
(`fee_levels.place_fees`, 2025 dollars, D-066 fill), median home value and gross rent from the newest ACS
5-year vintage <= origin (2025 dollars), and, where the state has a parcel roll, the median land value of
vacant residential lots (`scenarios.fees.parcel_inputs`, the roll's own dollars). Then
`pencil_out.table` for each place. No scenario is run and no outcome is read.
"""

from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path

import numpy as np
import pandas as pd

from lotline.config import load_fees
from lotline.io import DataStore
from lotline.model import money, pencil_out
from lotline.model.scenarios import adu, fees

ROOT = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("fee_dev_run", Path(__file__).with_name("fee_dev_run.py"))
dev = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(dev)

TYPE_NAMES = {"SFD": "House", "U2": "Duplex", "U3_4": "Fourplex"}
SUFFIX = {"SFD": "", "U2": "_U2", "U3_4": "_U3_4"}


def places_for(state: str, store, origin: int) -> pd.DataFrame | None:
    coded = load_fees(state)
    if coded is None:
        return None
    cpi = money.index_by_year(store.read(state, "market_geo_year"), "cpi_u")
    geoids = coded[["jurisdiction_geoid", "state"]].drop_duplicates()
    geoids = geoids.rename(columns={"jurisdiction_geoid": "geoid"})
    local = dev.type_fees(geoids, dev.all_coded_fees(), cpi)
    local = local[~local["geoid"].isin(dev.HOLDOUT_PLACES)].drop(columns="state")
    juris = store.read(state, "jurisdictions")[["geoid", "name", "kind", "state"]]
    places = local.merge(juris, on="geoid", how="left")
    places["acs_geo"] = places["kind"].map(adu.ACS_PREFIX) + ":" + places["geoid"]
    acs = adu.acs_values(store.read(state, "acs_geo_year"), places["acs_geo"], origin, cpi)
    places = places.merge(acs[["home_value", "rent"]], left_on="acs_geo", right_index=True, how="left")
    places["lot_value"] = np.nan
    places["new_home_value"] = np.nan
    parcels = store.read(state, "parcels")
    if parcels is not None:
        parcels = parcels[parcels["jurisdiction_geoid"].isin(places["geoid"])]
        pi = fees.parcel_inputs(parcels, origin, fees.central_params())
        med = pi.set_index("geoid")["lot_values"].map(
            lambda v: float(np.median(v)) if isinstance(v, np.ndarray) and len(v) else np.nan
        )
        places["lot_value"] = places["geoid"].map(med)
        places["new_home_value"] = places["geoid"].map(pi.set_index("geoid")["new_home_value"])
    return places


def money_(x) -> str:
    if pd.isna(x):
        return ""
    return f"−${-x:,.0f}" if x < 0 else f"${x:,.0f}"


def place_rows(places: pd.DataFrame) -> pd.DataFrame:
    out = []
    for _, r in places.iterrows():
        # new homes' value per sq ft from the parcel roll where there is one, else the ACS median home value
        new = r.get("new_home_value", np.nan)
        value, source = (
            (new, "parcel roll: new homes") if np.isfinite(new) else (r["home_value"], "ACS median")
        )
        if not (np.isfinite(value) and np.isfinite(r["rent"])):
            continue
        local = {t: r.get(f"local_fee_per_unit{s}", np.nan) for t, s in SUFFIX.items()}
        lot = r["lot_value"] if np.isfinite(r["lot_value"]) else None
        t = pencil_out.table(value, r["rent"], local, lot)
        out.append(t.assign(state=r["state"], geoid=r["geoid"], name=r["name"], value_source=source))
    return pd.concat(out, ignore_index=True) if out else pd.DataFrame()


def markdown(rows: pd.DataFrame, origin: int) -> str:
    lines = [
        "# Pencil-out: house, duplex and fourplex at today's fees and after a cut",
        "",
        "<!-- GENERATED by `uv run python scripts/dev/fee_pencil_out_table.py --out docs/research/fee-pencil-out.md`. Do not edit by hand. -->",
        "",
        f"For every place with coded fees (holdouts left out): the pro forma (`src/lotline/model/proforma.py`, central parameters) for a 2,150 sq ft house, a duplex and a fourplex of 1,000 sq ft units, in 2025 dollars, at the place's value of a new home (from the parcel roll where there is one: the median value per sq ft of detached homes built in the last 7 years, as the fee scenario's feasibility channel uses; else the ACS median home value, which covers older homes and so understates it) and ACS median gross rent (5-year vintage ending {origin} or earlier; also all units, so it understates a new unit's rent). Fees per unit by type from `config/fees/` under D-066 (filled where missing). **Residual land value** is what a builder can pay for the lot after value, construction, fees, interest and profit (`pencil_out.py`). **Fee share** is fees over construction + fees + interest. **Pencils** compares that with the median vacant residential lot's assessed land value plus a 10% margin, where the state has a parcel roll. The cut columns show the full fee change; how much builders keep (λ) is the fee scenario's question (D-073).",
        "",
        "## By state (for sale; medians over places)",
        "",
        "| State | Type | Places | Fee per unit | Fee per lot | Fee share of cost | Land value per lot today | Local fee cut in half | Handbook $50,000 | Handbook $25,000 | Pencils today / after the local cut |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    sale = rows[rows["tenure"] == "for_sale"]
    for (state, bt), g in sale.groupby(["state", "building_type"], sort=True):
        wide = g.pivot_table(index="geoid", columns="case", values="rlv_per_lot")
        now = g[g["case"] == "now"]
        half = g[g["case"] == "local_half"]
        pen = now["pencils"].dropna()
        pen_h = half["pencils"].dropna()
        pen_txt = (
            f"{int(pen.sum())} of {len(pen)} / {int(pen_h.sum())} of {len(pen_h)}"
            if len(pen)
            else "no lot values"
        )
        lines.append(
            f"| {state} | {TYPE_NAMES[bt]} | {now['geoid'].nunique()} | {money_(now['fee_per_unit'].median())} | "
            f"{money_(now['fee_per_lot'].median())} | {now['fee_share_of_cost'].median():.1%} | "
            + " | ".join(money_(wide[c].median()) if c in wide else "" for c in pencil_out.CASES)
            + f" | {pen_txt} |"
        )
    lines += [
        "",
        "## By place (for sale)",
        "",
        "| State | Place | Type | Fee per unit | Fee per lot | Fee share | Land value per lot: today | cut in half | $50,000 | $25,000 | Lot value | Pencils today | Value from |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for (state, name, bt), g in sale.groupby(["state", "name", "building_type"], sort=True):
        c = g.set_index("case")
        now = c.loc["now"] if "now" in c.index else None
        p = (
            ""
            if now is None or now["pencils"] is None or pd.isna(now["pencils"])
            else ("yes" if now["pencils"] else "no")
        )
        lines.append(
            f"| {state} | {name} | {TYPE_NAMES[bt]} | "
            + (
                f"{money_(now['fee_per_unit'])} | {money_(now['fee_per_lot'])} | {now['fee_share_of_cost']:.1%} | "
                if now is not None
                else "| | | "
            )
            + " | ".join(money_(c.loc[k, "rlv_per_lot"]) if k in c.index else "" for k in pencil_out.CASES)
            + f" | {money_(g['lot_value'].iloc[0])} | {p} | {g['value_source'].iloc[0]} |"
        )
    rent = rows[(rows["tenure"] == "rental") & (rows["case"].isin(["now", "local_half"]))]
    lines += [
        "",
        "## For rent (medians over places)",
        "",
        "| State | Type | Land value per unit today | after the local cut | Fee share of cost |",
        "|---|---|---|---|---|",
    ]
    for (state, bt), g in rent.groupby(["state", "building_type"], sort=True):
        w = g.pivot_table(index="geoid", columns="case", values="rlv_per_unit")
        share = g.loc[g["case"] == "now", "fee_share_of_cost"].median()
        lines.append(
            f"| {state} | {TYPE_NAMES[bt]} | {money_(w['now'].median())} | {money_(w['local_half'].median())} | {share:.1%} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--origin", type=int, default=2025)
    ap.add_argument("--state", nargs="+", default=["MN", "NC", "OH", "OR", "TX"])
    ap.add_argument("--out", type=Path)
    a = ap.parse_args()
    store = DataStore()
    frames = []
    for state in a.state:
        places = places_for(state, store, a.origin)
        if places is not None and not places.empty:
            frames.append(place_rows(places))
    rows = pd.concat([f for f in frames if not f.empty], ignore_index=True)
    text = markdown(rows, a.origin)
    if a.out:
        a.out.write_text(text)
        print(f"wrote {a.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
