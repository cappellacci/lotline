#!/usr/bin/env python3
# ruff: noqa: E501  (long report lines)
"""Coded local fees vs the Handbook's $50,000, by state, place and building type (D-065, office hours A4).

    uv run python scripts/dev/fee_levels_table.py [--out docs/research/fee-levels-vs-handbook.md]

Reads only config/fees/<st>.csv (every coded state, so pooled priors work), plus CPI-U and place names from the
local data store when it is there (amounts in 2025 dollars; otherwise nominal and labeled so). Not a model run:
no baseline, no scenario. For each coded place and building type it shows the coded fee per unit (range), the
fee after D-065's fill, and what the fill used; then a state summary against $50,000.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from lotline.config import CONFIG_DIR, load_fees, load_params
from lotline.model import fee_levels, money

TYPES = {"SFD": "House", "U2": "Duplex (per unit)", "U3_4": "3-4 units (per unit)", "ADU": "ADU"}
HOLDOUT_PLACES = {"2758000", "3712000"}  # St. Paul, Charlotte: shown, but flagged (their outcomes are holdouts)


def context():
    """(CPI-U index or None, geoid -> name)."""
    try:
        from lotline.io import DataStore

        store = DataStore()
        index = money.index_by_year(store.read("MN", "market_geo_year"), "cpi_u")
        names = {}
        for st in ("MN", "NC", "TX", "OR", "OH"):
            j = store.read(st, "jurisdictions")
            if j is not None:
                names.update(dict(zip(j["geoid"].astype(str), j["name"], strict=True)))
        return index, names
    except Exception as e:  # no local store: nominal dollars, geoids
        print(f"no data store ({e}); amounts stay nominal")
        return None, {}


def money_fmt(x: float) -> str:
    return "–" if pd.isna(x) else f"${x:,.0f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path)
    a = ap.parse_args()
    states = sorted(p.stem.upper() for p in (CONFIG_DIR / "fees").glob("*.csv"))
    fees = pd.concat([load_fees(s) for s in states], ignore_index=True)
    index, names = context()
    handbook = load_params("fees")["handbook_fee_per_unit_usd"].value
    places = fees[["jurisdiction_geoid", "state"]].drop_duplicates().rename(columns={"jurisdiction_geoid": "geoid"})
    out = fee_levels.all_types(places, fees, tuple(TYPES), index=index)
    coded = pd.concat(
        [fee_levels.coded_fees(fees, t, index=index) for t in TYPES], ignore_index=True
    ).set_index(["geoid", "building_type"])
    dollars = out["fee_dollars"].iloc[0]
    lines = [
        "# Coded local development fees vs the Handbook's $50,000",
        "",
        f"<!-- GENERATED by `uv run python scripts/dev/fee_levels_table.py --out {a.out or '...'}`. Do not edit by hand. -->",
        "",
        f"Fee per new unit in **{dollars}**, from `config/fees/<st>.csv` under the rules in `src/lotline/model/fee_levels.py` "
        "(D-065, D-066): per fee component the newest schedule year plus older rows still in force; a range where a fee "
        "varies by area, basin, tier or plat date; missing building-permit and water/sewer charges filled from the median "
        "of coded places (state if at least 5, else pooled), with the 25th–75th percentile as the range. The Handbook's "
        f"benchmark assumes **{money_fmt(handbook)}** per unit everywhere (D-065 reads it as 2025 dollars). "
        "Places marked † are holdouts for other tests; their fees are inputs, not outcomes.",
        "",
        "## By state (houses)",
        "",
        "| State | Coded places | Lowest | Median | Highest | Median as share of $50,000 | Places at or above $50,000 |",
        "|---|---|---|---|---|---|---|",
    ]
    sfd = out[out["building_type"] == "SFD"]
    for st, g in sfd.groupby("state"):
        v = g["local_fee_per_unit"]
        lines.append(
            f"| {st} | {len(g)} | {money_fmt(v.min())} | {money_fmt(v.median())} | {money_fmt(v.max())} | "
            f"{v.median() / handbook:.0%} | {(v >= handbook).sum()} |"
        )
    lines += ["", "## By place and building type", ""]
    for st, g in out.groupby("state"):
        lines += [
            f"### {st}",
            "",
            "| Place | Type | Coded fee (low–high) | After fill (low–high) | What was filled | Components (year) |",
            "|---|---|---|---|---|---|",
        ]
        for _, r in g.sort_values(["geoid", "building_type"]).iterrows():
            name = names.get(r["geoid"], r["geoid"]) + (" †" if r["geoid"] in HOLDOUT_PLACES else "")
            c = coded.loc[(r["geoid"], r["building_type"])] if (r["geoid"], r["building_type"]) in coded.index else None
            coded_txt = (
                "none coded"
                if c is None
                else f"{money_fmt(c['local_fee_per_unit'])} ({money_fmt(c['local_fee_low'])}–{money_fmt(c['local_fee_high'])})"
            )
            lines.append(
                f"| {name} | {TYPES[r['building_type']]} | {coded_txt} | {money_fmt(r['local_fee_per_unit'])} "
                f"({money_fmt(r['local_fee_low'])}–{money_fmt(r['local_fee_high'])}) | {r['fee_source']} | "
                f"{r['fee_years'].replace(',', ', ')} |"
            )
        lines.append("")
    text = "\n".join(lines).rstrip() + "\n"
    if a.out:
        a.out.write_text(text)
        print(f"wrote {a.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
