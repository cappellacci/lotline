def generate(
    places: pd.DataFrame,
    counties: pd.DataFrame,
    metro: set[str],
    late: dict[str, tuple[str, str, str]] | None = None,
    checks: pd.DataFrame | None = None,
) -> pd.DataFrame:
    """All generated rows. `late`: cities moved from the 2,500-10,000 tier to HB 2001's medium tier
    (`PSU_MEDIUM`); `checks`: validation verdicts (jurisdiction_geoid, theme, verdict, note) added to the
    rows they cover (`apply_checks`)."""
    late = late or {}
    t = tiers(places, counties, metro)
    moved = t["small"][t["small"]["geoid"].isin(late)]
    t["small"] = t["small"][~t["small"]["geoid"].isin(late)]
    rows = adu_rows(t["adu_cities"], county=False) + adu_rows(t["adu_counties"], county=True)
    rows += middle_rows(t["large"], "large") + middle_rows(t["large_counties"], "large", county=True)
    rows += middle_rows(t["medium"], "medium") + middle_rows(moved, "medium", late=late)
    rows += middle_rows(t["small"], "small")
    prior = {r["jurisdiction_geoid"]: r["reform_id"] for r in rows if r["reform_id"].endswith("-landdiv")}
    rows += hb2138_rows(t["large_2027"], prior)
    out = pd.DataFrame(rows, columns=COLUMNS).sort_values("reform_id", ignore_index=True)
    return apply_checks(out, checks) if checks is not None else out


def checked(row: pd.Series) -> bool:
    """The rows Ben's validation agent checked on 2026-11-05: the 2,500-10,000 duplex tier (and the three
    cities moved out of it) with their land-division rows, and the counties' SB 1051 ADU rows."""
    rid = row["reform_id"]
    if row["theme"] == "adu":
        return len(row["jurisdiction_geoid"]) == 5 and rid.endswith("-adu-2018")
    return rid.endswith(("-missing_middle-2025", "-missing_middle-2025-landdiv")) or (
        row["jurisdiction_geoid"] in PSU_MEDIUM and "-missing_middle-2027" not in rid
    )


def apply_checks(rows: pd.DataFrame, checks: pd.DataFrame) -> pd.DataFrame:
    """Mark each checked row verified and add the verdict to its notes. Every check must find its rows."""
    out = rows.copy()
    note = checks.set_index(["jurisdiction_geoid", "theme"])
    hit = set()
    for i, r in out.iterrows():
        key = (r["jurisdiction_geoid"], r["theme"])
        if key not in note.index or not checked(r):
            continue
        c = note.loc[key]
        out.loc[i, ["verified_by", "verified_date"]] = [CHECKED_BY, CHECKED_ON]
        out.loc[i, "coding_notes"] += f" Validation {CHECKED_ON} ({c['verdict']}): {c['note']}"
        hit.add(key)
    missing = set(note.index) - hit
    if missing:
        raise ValueError(f"validation rows match no generated row: {sorted(missing)}")
    return out


# --- inputs and output ------------------------------------------------------------------------------------


def census_inputs() -> tuple[pd.DataFrame, pd.DataFrame]:
    from lotline.adapters.national import decennial
    from lotline.io import DataStore

    d = decennial.load("41", "OR", DataStore())
    p = d[d["geoid"].str.len() == 7]
    p = p[p["census_name"].str.endswith((" city", " town"))]  # incorporated only (no CDPs)
    places = pd.DataFrame(
        {
            "geoid": p["geoid"],
            "name": p["census_name"].str.replace(r" (city|town)$", "", regex=True),
            "pop": p["pop_2020"],
        }
    )
    c = d[d["geoid"].str.len() == 5]
    counties = pd.DataFrame(
        {"geoid": c["geoid"], "name": c["census_name"].str.replace(" County", ""), "pop": c["pop_2020"]}
    )
    return places.reset_index(drop=True), counties.reset_index(drop=True)


def merged(generated: pd.DataFrame, path: Path = OUT) -> pd.DataFrame:
    if path.exists():
        old = pd.read_csv(path, dtype=str, keep_default_na=False)
        local = old[~old["coding_notes"].str.startswith(GENERATED)]
    else:
        local = pd.DataFrame(columns=COLUMNS)
    return pd.concat([local, generated], ignore_index=True)[COLUMNS]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if or.csv's generated rows are out of date")
    args = ap.parse_args(argv)
    places, counties = census_inputs()
    metro = set(pd.read_csv(METRO, dtype=str)["geoid"])
    checks = pd.read_csv(CHECKS, dtype=str, keep_default_na=False)
    out = merged(generate(places, counties, metro, late=PSU_MEDIUM, checks=checks))
    text = out.to_csv(index=False, lineterminator="\n")
    if args.check:
        same = OUT.exists() and OUT.read_text() == text
        print("or.csv is up to date" if same else "or.csv is out of date: rerun the script")
        return 0 if same else 1
    OUT.write_text(text)
    n = out["coding_notes"].str.startswith(GENERATED).sum()
    print(f"wrote {OUT.relative_to(ROOT)}: {n} generated rows, {len(out) - n} local rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
