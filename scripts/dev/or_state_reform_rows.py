GENERATED = "GENERATED by scripts/dev/or_state_reform_rows.py."
METRO_COUNTIES = {"41005": "Clackamas", "41051": "Multnomah", "41067": "Washington"}

CHECKS = ROOT / "docs" / "research" / "ordinances" / "or-state-law-check-2026-11-05.csv"
CHECKED_BY = "Ben's ordinance-validation agent"
CHECKED_ON = "2026-11-05"

