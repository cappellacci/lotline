def hb2138_rows(j: pd.DataFrame, prior: dict[str, str]) -> list[dict]:
    rows = []
    for g, name in zip(j["geoid"], j["name"], strict=True):
        rows.append(
            _row(
                g,
                "2027",
                "missing_middle",
                component=(
                    "HB 2138 (2025) §1, ORS 197A.420(2): all middle housing types on each lot zoned for "
                    "residential use, attached or detached in any configuration, keeping an existing house, "
                    "house plus ADU or duplex; one or two bonus units for an accessible or affordable unit "
                    "(§3)"
                ),
                effective_date="2027-01-01",
                supersedes=prior.get(g),
                unit_cap="4",
                coverage=(
                    f"City of {name}: each lot or parcel zoned for residential use inside the urban growth "
                    "boundary"
                ),
                source_url=HB2138,
                source_section="HB 2138 (2025) §1(1)-(4), §3; compliance deadline §4(1)(e)",
                source_quote=(
                    "each city with a population of 25,000 or greater , and each city with a population of "
                    "1,000 "
                    "or greater within Metro, shall allow the development of all middle housing types on "
                    "each lot "
                    "or parcel zoned for residential use"
                ),
                coding_notes=(
                    f"{GENERATED} Effective on passage (emergency clause, §53; signature date not in the "
                    "enrolled "
                    "text); cities must conform by 2027-01-01 (§4(1)(e)), cottage-cluster changes by "
                    "2028-01-01. "
                    "unit_cap stays 4: the §3 bonus (+1 or +2 units, up to 6) needs an accessible or "
                    "covenanted "
                    "affordable unit. Not coded: HB 2138's extension to every county's urban unincorporated "
                    "land "
                    f"outside Metro. {POP_NOTE} {READ_NOTE}"
                ),
            )
        )
    return rows


def generate(places: pd.DataFrame, counties: pd.DataFrame, metro: set[str]) -> pd.DataFrame:
    t = tiers(places, counties, metro)
    rows = adu_rows(t["adu_cities"], county=False) + adu_rows(t["adu_counties"], county=True)
    rows += middle_rows(t["large"], "large") + middle_rows(t["large_counties"], "large", county=True)
    rows += middle_rows(t["medium"], "medium") + middle_rows(t["small"], "small")
    prior = {r["jurisdiction_geoid"]: r["reform_id"] for r in rows if r["reform_id"].endswith("-landdiv")}
    rows += hb2138_rows(t["large_2027"], prior)
    return pd.DataFrame(rows, columns=COLUMNS).sort_values("reform_id", ignore_index=True)


# --- inputs and output ------------------------------------------------------------------------------------


def census_inputs() -> tuple[pd.DataFrame, pd.DataFrame]:
    from lotline.adapters.national import decennial
    from lotline.io import DataStore

    d = decennial.load("41", "OR", DataStore())
    p = d[d["geoid"].str.len() == 7]
    p = p[p["census_name"].str.endswith((" city", " town"))]  # incorporated only (no CDPs)
    places = pd.DataFrame(
        {
            "geoid": p["geoid"],
            "name": p["census_name"].str.replace(r" (city|town)$", "", regex=True),
            "pop": p["pop_2020"],
        }
    )
    c = d[d["geoid"].str.len() == 5]
    counties = pd.DataFrame(
        {"geoid": c["geoid"], "name": c["census_name"].str.replace(" County", ""), "pop": c["pop_2020"]}
    )
    return places.reset_index(drop=True), counties.reset_index(drop=True)


def merged(generated: pd.DataFrame, path: Path = OUT) -> pd.DataFrame:
    if path.exists():
        old = pd.read_csv(path, dtype=str, keep_default_na=False)
        local = old[~old["coding_notes"].str.startswith(GENERATED)]
    else:
        local = pd.DataFrame(columns=COLUMNS)
    return pd.concat([local, generated], ignore_index=True)[COLUMNS]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if or.csv's generated rows are out of date")
    args = ap.parse_args(argv)
    places, counties = census_inputs()
    metro = set(pd.read_csv(METRO, dtype=str)["geoid"])
    out = merged(generate(places, counties, metro))
    text = out.to_csv(index=False, lineterminator="\n")
    if args.check:
        same = OUT.exists() and OUT.read_text() == text
        print("or.csv is up to date" if same else "or.csv is out of date: rerun the script")
        return 0 if same else 1
    OUT.write_text(text)
    n = out["coding_notes"].str.startswith(GENERATED).sum()
    print(f"wrote {OUT.relative_to(ROOT)}: {n} generated rows, {len(out) - n} local rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
