"""Generate Oregon's state-law rows in `config/reforms/or.csv`, one row per covered jurisdiction.

Oregon's ADU and middle-housing laws cover places by city size, Metro membership and county size, which one
statewide row (`jurisdiction_geoid = "41"`) can't express. So each covered city, town or county remainder gets
its own row, citing the statute. Rows written here carry `GENERATED` at the start of `coding_notes`; every
other row in the file (local ordinances) is kept as is.

Inputs: 2020 Census P.L. 94-171 population (`decennial`, through the data store) and
`config/crosswalks/or_metro_cities.csv` (Metro's 24 cities). Statute text was read from the enrolled bills and
session laws (WS-OR, 2026-11-04); thresholds and dates below quote them.

    python scripts/dev/or_state_reform_rows.py          # rewrite the generated rows
    python scripts/dev/or_state_reform_rows.py --check  # exit 1 if the file is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "config" / "reforms" / "or.csv"
METRO = ROOT / "config" / "crosswalks" / "or_metro_cities.csv"
GENERATED = "GENERATED by scripts/dev/or_state_reform_rows.py."
METRO_COUNTIES = {"41005": "Clackamas", "41051": "Multnomah", "41067": "Washington"}

SB1051 = "https://olis.oregonlegislature.gov/liz/2017R1/Downloads/MeasureDocument/SB1051/Enrolled"
HB2001 = "https://www.oregonlegislature.gov/bills_laws/lawsstatutes/2019orLaw0639.pdf"
SB458 = "https://olis.oregonlegislature.gov/liz/2021R1/Downloads/MeasureDocument/SB458/Enrolled"
ORS197A = "https://www.oregonlegislature.gov/bills_laws/ors/ors197A.html"
HB2138 = "https://olis.oregonlegislature.gov/liz/2025R1/Downloads/MeasureDocument/HB2138/Enrolled"

POP_NOTE = (
    "Tier from 2020 Census population (P.L. 94-171); the statutes don't say how population is measured "
    "(DLCD uses Portland State University certified estimates), so a city near a threshold may be "
    "misassigned."
)
READ_NOTE = (
    "Statute read 2026-11-04 from an archived copy of the official text (oregonlegislature.gov did not "
    "answer from our network); second coder pending."
)

COLUMNS = (
    "reform_id,state,jurisdiction_geoid,theme,component,status,announced_date,adoption_date,effective_date,"
    "end_date,supersedes,by_right,owner_occ,unit_cap,far_cap,max_stories,min_lot_sqft,adu_max_sqft,"
    "adu_detached_allowed,adus_per_lot,lot_split,parking,parking_min_per_unit,fee_change_usd,dollar_year,"
    "coverage,coverage_zones,source_url,source_section,source_quote,verified_by,verified_date,coder,coder_2,"
    "coder_agreement,coding_notes"
).split(",")


# --- who each law covers -----------------------------------------------------------------------------------


def tiers(places: pd.DataFrame, counties: pd.DataFrame, metro: set[str]) -> dict[str, pd.DataFrame]:
    """Jurisdictions covered by each state law.

    `places`: geoid, name, pop (incorporated cities and towns only); `counties`: geoid (5-digit), name, pop.
    """
    in_metro = places["geoid"].isin(metro)
    return {
        # SB 1051 §6(5)(a): "A city with a population greater than 2,500 or a county with a population greater
        # than 15,000". Counties: the unincorporated remainder (5-digit GEOID).
        "adu_cities": places[places["pop"] > 2500],
        "adu_counties": counties[counties["pop"] > 15000],
        # HB 2001 §2(2) "each city with a population of 25,000 or more and each county or city within a
        # metropolitan service district", less §2(4)(a) cities of 1,000 or fewer.
        "large": places[(places["pop"] >= 25000) | (in_metro & (places["pop"] > 1000))],
        "large_counties": counties[counties["geoid"].isin(METRO_COUNTIES)],
        # HB 2001 §2(3): "each city not within a metropolitan service district with a population of more than
        # 10,000 and less than 25,000" (duplexes).
        "medium": places[~in_metro & (places["pop"] > 10000) & (places["pop"] < 25000)],
        # 2023 c.223 §20 (ORS 197A.420(3)): the duplex tier now starts at "2,500 or greater"; newly covered
        # cities by June 30, 2025.
        "small": places[~in_metro & (places["pop"] >= 2500) & (places["pop"] <= 10000)],
        # HB 2138 (2025) §1(2): "each city with a population of 25,000 or greater, and each city with a
        # population of 1,000 or greater within ... Metro".
        "large_2027": places[(places["pop"] >= 25000) | (in_metro & (places["pop"] >= 1000))],
    }


# --- rows ------------------------------------------------------------------------------------------------


def _row(geoid: str, suffix: str, theme: str, **fields) -> dict:
    row = {c: "" for c in COLUMNS}
    row.update(
        reform_id=f"OR-{geoid}-{theme}-{suffix}",
        state="OR",
        jurisdiction_geoid=geoid,
        theme=theme,
        status="in_force",
        coder="claude",
        coder_agreement="single_coder",
    )
    row.update({k: v for k, v in fields.items() if v is not None})
    return row


def _where(name: str, county: bool) -> str:
    return f"Unincorporated {name} County" if county else f"City of {name}"


def adu_rows(j: pd.DataFrame, county: bool) -> list[dict]:
    rows = []
    for g, name in zip(j["geoid"], j["name"], strict=True):
        where = _where(name, county)
        ugb = " inside the urban growth boundary" if county else ""
        first = _row(
            g,
            "2018",
            "adu",
            component=(
                "SB 1051 (2017) §6, ORS 197.312(5): at least one ADU (interior, attached or detached) per "
                "detached single-family dwelling, subject to reasonable local siting and design rules"
            ),
            effective_date="2018-07-01",
            adu_detached_allowed="True",
            adus_per_lot="1",
            coverage=f"{where}: areas zoned for detached single-family dwellings{ugb}",
            source_url=SB1051,
            source_section="SB 1051 (2017) §6 (ORS 197.312(5)(a)-(b)); operative July 1, 2018 (§12, §13(3))",
            source_quote=(
                "A city with a population greater than 2,500 or a county with a population greater than "
                "15,000 shall allow in areas zoned for detached single-family dwellings the development of "
                "at "
                "least one accessory dwelling unit for each detached single-family dwelling"
            ),
            coding_notes=(
                f"{GENERATED} Applies to ADU applications submitted on or after 2018-07-01 (§13(3)). The act "
                "took effect on passage (emergency clause, §14); the signature date is not in the enrolled "
                "text, "
                "so adoption_date is blank. Owner occupancy and parking were left to local rules until 2020 "
                "(blank here). The 'within the urban growth boundary' wording came from 2018 c.15 (not "
                "read). "
                f"{POP_NOTE} {READ_NOTE}"
            ),
        )
        second = _row(
            g,
            "2020",
            "adu",
            component=(
                "HB 2001 (2019) §7, ORS 197.312(5)(b)(B): local siting and design rules may not require "
                "owner "
                "occupancy or additional off-street parking for an ADU"
            ),
            adoption_date="2019-08-08",
            effective_date="2020-01-01",
            supersedes=first["reform_id"],
            owner_occ="False",
            parking="no additional off-street parking may be required",
            parking_min_per_unit="0",
            coverage=(
                f"{where}: areas within the urban growth boundary zoned for detached single-family dwellings"
            ),
            source_url=HB2001,
            source_section=(
                "Oregon Laws 2019 c.639 §7 (ORS 197.312(5)-(6)); operative January 1, 2020 (§14(1))"
            ),
            source_quote=(
                "“Reasonable local regulations relating to siting and design” does not include "
                "owner-occupancy "
                "requirements of either the primary or accessory structure or requirements to construct "
                "additional off-street parking."
            ),
            coding_notes=(
                f"{GENERATED} Approved and effective 2019-08-08 (emergency clause, §16); operative "
                "2020-01-01. "
                "Owner occupancy and parking may still be required for vacation occupancies (§7(6)). Other "
                "fields "
                f"inherit from {first['reform_id']}. {POP_NOTE} {READ_NOTE}"
            ),
        )
        rows += [first, second]
    return rows


