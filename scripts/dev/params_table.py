#!/usr/bin/env python3
"""Write the parameter table in docs/model_and_assumptions.md from config/params/*.yaml.

Every model parameter lives in a YAML file with a value, a low-high range, a unit and a source. This script
renders them as Markdown tables (one per file) and puts them between the markers

    <!-- params-table:start -->
    <!-- params-table:end -->

so the document can never disagree with the config. Standard library plus the project's own loader.

    uv run python scripts/dev/params_table.py           # rewrite the table in the document
    uv run python scripts/dev/params_table.py --check   # exit 1 if the document's table is out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from lotline.config import CONFIG_DIR, Parameter, load_params

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs" / "model_and_assumptions.md"
START = "<!-- params-table:start -->"
END = "<!-- params-table:end -->"
SENTENCE_END = re.compile(r"(?<![.])\. (?=[A-Z])")
SOURCE_CHARS = 110  # longest source shown; the full text stays in the YAML file


def fmt_number(x: float, unit: str) -> str:
    """A readable number: no trailing .0, thousands separators except for years and seeds."""
    if float(x).is_integer():
        n = int(x)
        plain = "year" in unit or "seed" in unit
        return str(n) if plain or abs(n) < 1_000 else f"{n:,}"
    return f"{x:g}"


def short_source(source: str, limit: int = SOURCE_CHARS) -> str:
    """The first clause of a source (up to the first '; ' or sentence end), cut at `limit` characters."""
    text = " ".join(source.split())
    text = text.split("; ", 1)[0]
    text = SENTENCE_END.split(text, 1)[0]  # a full stop before a capital, not "..." or "approx."
    if len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def file_table(name: str, params: dict[str, Parameter]) -> str:
    """One Markdown table for config/params/<name>.yaml, in file order."""
    lines = [
        f"**`config/params/{name}.yaml`** ({len(params)} parameter{'' if len(params) == 1 else 's'})",
        "",
        "| Parameter | Value | Range (low–high) | Unit | Source (short; full text in the file) |",
        "|---|---|---|---|---|",
    ]
    for key, p in params.items():
        value = fmt_number(p.value, p.unit)
        rng = "fixed" if p.low == p.high else f"{fmt_number(p.low, p.unit)}–{fmt_number(p.high, p.unit)}"
        lines.append(f"| `{key}` | {value} | {rng} | {cell(p.unit)} | {cell(short_source(p.source))} |")
    return "\n".join(lines)


def render(config_dir: Path = CONFIG_DIR) -> str:
    """Every params file, alphabetically, as Markdown (no markers)."""
    names = sorted(p.stem for p in (config_dir / "params").glob("*.yaml"))
    tables = {name: load_params(name, config_dir) for name in names}
    total = sum(len(t) for t in tables.values())
    files = f"{len(names)} file" + ("" if len(names) == 1 else "s")
    head = (
        "<!-- GENERATED by `uv run python scripts/dev/params_table.py` from config/params/*.yaml. "
        f"Do not edit by hand. -->\n\n{total} parameters in {files}. "
        '"Fixed" means the value is set by the Handbook, the validation plan or a definition '
        "and is not varied."
    )
    return head + "\n\n" + "\n\n".join(file_table(n, t) for n, t in tables.items())


def splice(doc: str, table: str) -> str:
    """Replace whatever sits between the markers with `table`."""
    if doc.count(START) != 1 or doc.count(END) != 1 or doc.index(START) > doc.index(END):
        raise ValueError(f"the document needs exactly one {START} ... {END} pair")
    before, rest = doc.split(START, 1)
    _, after = rest.split(END, 1)
    return f"{before}{START}\n{table}\n{END}{after}"


def main(argv: list[str] | None = None, doc_path: Path = DOC, config_dir: Path = CONFIG_DIR) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the table is out of date")
    args = parser.parse_args(argv)
    doc = doc_path.read_text()
    new = splice(doc, render(config_dir))
    if args.check:
        if new != doc:
            print(f"{doc_path.name}: parameter table is out of date; run scripts/dev/params_table.py")
            return 1
        print(f"{doc_path.name}: parameter table is up to date")
        return 0
    if new != doc:
        doc_path.write_text(new)
        print(f"wrote the parameter table in {doc_path}")
    else:
        print(f"{doc_path.name}: parameter table already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
